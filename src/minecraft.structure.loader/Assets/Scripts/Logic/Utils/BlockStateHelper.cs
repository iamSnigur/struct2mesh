        public static OffsetType GetOffsetType(string blockId)
        {
            if (XYZOffsetBlocks.Contains(blockId))
                return OffsetType.XYZ;

            if (XZOffsetBlocks.Contains(blockId))
                return OffsetType.XZ;

            return OffsetType.NONE;
        }

